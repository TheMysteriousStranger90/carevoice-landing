import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { DomSanitizer, SafeResourceUrl } from '@angular/platform-browser';
import { SECTIONS } from '../../content/site';
import { RevealDirective } from '../../directives/reveal.directive';

interface Shot {
  type: 'video' | 'image';
  /** Fallback / poster image. */
  src: string;
  /** Responsive candidates (local WebP only). */
  srcset?: string;
  /** Intrinsic size of `src`, so the browser reserves space and avoids layout shift. */
  width: number;
  height: number;
  url: string;
  caption: string;
  youtubeId?: string;
}

/** Local screenshots are generated by `npm run images` at 800 px and 1600 px wide. */
const SHOT_WIDTH = 1600;
const SHOT_HEIGHT = 726;

function screenshot(name: string, url: string, caption: string): Shot {
  return {
    type: 'image',
    src: `screenshots/${name}-1600.webp`,
    srcset: `screenshots/${name}-800.webp 800w, screenshots/${name}-1600.webp 1600w`,
    width: SHOT_WIDTH,
    height: SHOT_HEIGHT,
    url,
    caption
  };
}

/** YouTube video ids are exactly 11 URL-safe characters. */
const YOUTUBE_ID = /^[\w-]{11}$/;

